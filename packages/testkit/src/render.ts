// The snapshot renderer. Output depends only on the run, which depends only on the fixture and its
// seed: times are offsets on the simulated clock, IDs come from the seeded generator, and rows and
// columns have a fixed order. Nothing here reads the machine's clock or randomness.
import type { JudgmentView, PanelMemberView } from './judgment.js';
import type { Outcome, Prefix } from './prefix.js';
import { fenced, mdText } from './untrusted.js';
import type { Scenario } from './scenario.js';
import type { StubRun } from './stub-settlement.js';
import { TOKEN, TOKEN_DECIMALS } from './stub-terms.js';

const PREFIX_TEXT: Record<Prefix, string> = {
  normal: 'none (normal flow: reaches a terminal state, invariants hold)',
  error: 'error. (the system must refuse a step; invariants hold)',
  attack: 'attack. (adversarial input: must not auto-accept)',
  neutrality: 'neutrality. (an actor fails: terms-compliant terminal state anyway)',
  todo: 'todo. (known gap: records current behavior)',
};

export const short = (hex: string): string => (hex.length > 12 ? `${hex.slice(0, 6)}…${hex.slice(-4)}` : hex);

/** Base units to a grouped decimal with the token's decimals, e.g. 2000000000 → 2,000.000000. */
export function formatAmount(units: bigint): string {
  if (units === 0n) return '0';
  const negative = units < 0n;
  const abs = negative ? -units : units;
  const scale = 10n ** BigInt(TOKEN_DECIMALS);
  const whole = (abs / scale).toString().replace(/\B(?=(\d{3})+(?!\d))/g, ',');
  const frac = (abs % scale).toString().padStart(TOKEN_DECIMALS, '0');
  return `${negative ? '-' : ''}${whole}.${frac}`;
}

/** Simulated elapsed time as mm:ss.mmm (minutes grow past 59 rather than wrapping). */
export function formatElapsed(ms: number): string {
  const minutes = Math.floor(ms / 60_000);
  const seconds = Math.floor((ms % 60_000) / 1000);
  const millis = ms % 1000;
  return `${String(minutes).padStart(2, '0')}:${String(seconds).padStart(2, '0')}.${String(millis).padStart(3, '0')}`;
}

const cell = (s: string): string => s.replaceAll('|', '\\|').replaceAll('\n', ' ');
const table = (header: string[], rows: string[][]): string[] => [
  `| ${header.join(' | ')} |`,
  `| ${header.map(() => '---').join(' | ')} |`,
  ...rows.map((r) => `| ${r.map(cell).join(' | ')} |`),
];
const mark = (ok: boolean): string => (ok ? '✓' : '✗');

export function renderSnapshot(scenario: Scenario, prefix: Prefix, run: StubRun, outcome: Outcome): string {
  const { pragmas, parties, adjudicators } = scenario;
  const who = (name: string) => {
    const a = run.actors.find((x) => x.name === name);
    return a ? `${name} ${short(a.address)}` : name;
  };
  const ref = (path: string | undefined, what: string, loaded: boolean) =>
    loaded ? `${path} (loaded)` : path ? `${path} (stub ${what}; file absent)` : `built-in stub ${what}`;
  const c = run.commitment;
  const out: string[] = [
    `# ${scenario.name}`,
    '',
    '> Generated by `pnpm snap` (packages/testkit). Do not edit by hand: run `pnpm snap --update ' + scenario.name + '` and review the diff.',
    '',
  ];
  if (scenario.description) out.push(scenario.description, '');

  out.push('## Input', '');
  out.push(
    ...table(
      ['Field', 'Value'],
      [
        ['Pragmas', `settlement=${pragmas.settlement} · judges=${pragmas.judges} · mode=${pragmas.mode} · seed=${pragmas.seed}`],
        ['Prefix', PREFIX_TEXT[prefix]],
        ['Settlement', 'SimChain (T-006) driving @holdback/core `step`'],
        [
          'Judgment',
          c
            ? `@holdback/judgment (checks, screen, panel) · registry config/judges.yaml ${short(c.terms.adjudication.registryHash)} · policy ${c.terms.adjudication.policyId} ${short(c.terms.adjudication.policyHash)}`
            : '@holdback/judgment (checks, screen, panel) · registry config/judges.yaml',
        ],
        ['Club', `${ref(scenario.club, 'rulebook', run.loaded.club)} · rulebook ${short(run.rulebookHash)}`],
        ['Buyer', who(parties.buyer)],
        ['Seller', who(parties.seller)],
        [
          'Terms',
          c
            ? `${ref(scenario.terms, 'terms', run.loaded.terms)} · commitment ${short(c.id)} · price ${formatAmount(BigInt(c.terms.price.amount))} ${TOKEN} · fee ${formatAmount(BigInt(c.terms.adjudication.fee.amount))} ${TOKEN}`
            : `${ref(scenario.terms, 'terms', run.loaded.terms)} · no commitment created`,
        ],
        ['Adjudicators', `primary ${who(adjudicators.primary)} · fallback ${who(adjudicators.fallback)} · appeal ${who(adjudicators.appeal)}`],
        ['Operators', scenario.operators.length ? scenario.operators.join(' · ') : 'none'],
        ...run.others.map((o) => [`Commitment #${o.n}`, `same terms, new nonce · commitment ${short(o.id)}`]),
      ],
    ),
    '',
  );

  out.push('## Timeline', '');
  if (run.rows.length === 0) out.push('No calls.');
  else
    out.push(
      ...table(
        ['t (sim)', 'Step', 'Actor', 'Call', 'Via', 'Result', 'State'],
        run.rows.map((r) => [formatElapsed(r.t), String(r.step), r.actor, r.call, r.via, r.result, r.state]),
      ),
    );
  const refusals = run.rows.filter((r) => r.detail !== undefined);
  if (refusals.length) out.push('', 'Refusals:', '', ...refusals.map((r) => `- Step ${r.step} ${r.call}: ${r.result}: ${mdText(r.detail!)}`));
  if (run.outages.length) out.push('', 'Outages:', '', ...run.outages.map((o) => `- Step ${o.step}: ${o.actor} ${o.kind === 'offline' ? 'is offline' : o.kind === 'operator_refused' ? 'refused to relay' : 'timed out; a permissionless timeout acted instead'}`));
  out.push('');

  out.push(`## Balances (${TOKEN})`, '');
  out.push(...table(['After', ...run.accounts], run.balanceRows.map((r) => [r.after, ...run.accounts.map((a) => formatAmount(r.balances[a] ?? 0n))])), '');

  out.push('## Judgment', '');
  if (run.judgments.length === 0) out.push('- No judgment ran.');
  for (const j of run.judgments) out.push(...renderJudgment(j), '');
  if (run.judgments.length === 0) out.push('');

  out.push('## Receipts and log', '');
  const head = run.events.at(-1);
  out.push(
    head
      ? `- Events 0–${head.seq}. Chain head ${short(head.hash)}. Replay of ${run.replay.events} SimChain submissions from genesis ${run.replay.ok ? 'matches' : 'DOES NOT match'} the settlement state.`
      : '- No events.',
  );
  const byOperator = new Map<string, string[]>();
  for (const r of run.receipts) byOperator.set(r.operator, [...(byOperator.get(r.operator) ?? []), r.id]);
  if (byOperator.size === 0) out.push('- No operator receipts.');
  for (const [op, ids] of [...byOperator].sort(([a], [b]) => (a < b ? -1 : 1))) {
    out.push(`- Receipts from ${op}: ${ids.length} (${ids[0]}–${ids.at(-1)}). The runner labels them without signing; the operator API signs real receipts.`);
  }
  out.push('');

  out.push('## Invariants', '');
  out.push(`- ${run.invariants.map((i) => `${i.name} ${i.note ?? mark(i.ok)}`).join(' · ')}`, '');

  out.push('## Outcome', '');
  out.push(`- Final state: ${run.finalState ?? 'no commitment'}${run.others.map((o) => `; commitment #${o.n}: ${o.finalState}`).join('')}.`);
  out.push(`- Prefix expectations: ${outcome.label}${outcome.reasons.length ? `: ${outcome.reasons.map(mdText).join('; ')}` : ''}.`);
  return `${out.join('\n')}\n`;
}

const SOURCE_TEXT: Record<string, string> = { fake: ' (captured from fake judges)', authored: ' (authored)', live: '' };

/** One panel seat: who judged, with which pinned model, where the verdict came from, and what it said. */
export function renderMember(m: PanelMemberView): string {
  const source = m.source === 'recorded' ? `recorded${SOURCE_TEXT[m.capturedFrom ?? 'live'] ?? ''}` : 'fake judge';
  const said = m.overall === null ? `no verdict (${m.status})` : m.overall === 'abstain' ? 'abstain' : `${m.overall} · scores ${m.scores.join('/')}`;
  const flag = m.injectionSuspected ? ' · injection suspected' : '';
  return `  - ${m.judgeId} · ${m.provider}/${m.family} · ${m.model} · ${source} · ${said}${flag} · input ${short(m.inputHash)}`;
}

/** ADR-0018: where the panel seed came from, and whether it recomputes. */
export function seedSourceText(p: JudgmentView['panel']): string {
  if (p.seedSource === 'commit-reveal') {
    return `seed source: commit-reveal (commitment ${p.seedCommitment === null ? 'none' : short(p.seedCommitment)}, seed ${short(p.seed)}, recomputed: ${p.seedMatches ? 'match' : 'MISMATCH'})`;
  }
  return p.beaconRound === null ? `seed source: beacon, round not yet published (seed ${short(p.seed)})` : `seed source: beacon round ${p.beaconRound} (seed ${short(p.seed)})`;
}

export function renderJudgment(j: JudgmentView): string[] {
  const p = j.panel;
  const a = j.aggregate;
  const intake = j.intake.refused
    ? `refused (${j.intake.refused})`
    : `hash verified ${mark(j.intake.hashVerified)}${j.intake.normalized ? ' · normalized' : ''}`;
  const checks = j.checks.length
    ? j.checks.map((ch) => `${ch.id}${ch.required ? '' : ' (optional)'} ${mark(ch.passed)}${!ch.passed && ch.detail ? ` (${mdText(ch.detail)})` : ''}`).join(' · ')
    : 'not run';
  const screen = j.checks.length === 0 && !j.screen.flagged ? 'not run' : j.screen.flagged ? `flagged: ${j.screen.signals.map((s) => `${s.kind}${s.detail ? ` (${mdText(s.detail)})` : ''}`).join('; ')}` : 'clean';
  const panelHead = `${p.template} template ${short(p.promptTemplateHash)} · rubric ${short(p.rubricHash)} · ${seedSourceText(p)}`;
  const counts = a.validCount === undefined ? '' : `; ${a.passCount} pass, ${a.failCount} fail of ${a.validCount} valid${a.passFamilies?.length ? `; pass families ${a.passFamilies.join(', ')}` : ''}`;
  const score = a.weightedScore === null ? '' : `weighted score ${(a.weightedScore / 100).toFixed(2)}`;
  const detail = [score, counts.slice(2)].filter(Boolean).join('; ');
  return [
    `### ${j.adjudicator} (${j.role}), attempt ${j.attempt}`,
    '',
    `- **Intake:** plaintext ${short(j.intake.plaintextSha256.replace('sha256:', '0x'))} · ${j.intake.mime} · ${j.intake.bytes} bytes (${j.intake.source}) · ${intake}`,
    `- **Deterministic checks:** ${checks}`,
    `- **Screen:** ${screen}`,
    p.ran
      ? `- **Panel:** ${p.members.length} judges from ${new Set(p.members.map((m) => m.family)).size} families (policy: ${p.size} seats, at least ${p.minFamilies} families) · ${panelHead}`
      : `- **Panel:** not run · ${panelHead}`,
    ...p.members.map(renderMember),
    `- **Aggregate:** ${a.decision}${detail ? ` (${detail})` : ''}. Reasons: ${a.reasons.map(mdText).join('; ')}.`,
    `- **Signed:** ${j.outcome === null ? 'no decision (an appeal panel cannot escalate; the default outcome applies)' : j.outcome === a.decision ? j.outcome : `${j.outcome} (the first decision stands: an appeal panel cannot escalate)`}.`,
  ];
}

/** The snapshot of a todo. fixture the runner cannot run yet: it records the error as today's behavior. */
export function renderErrorSnapshot(name: string, error: Error): string {
  return [
    `# ${name}`,
    '',
    '> Generated by `pnpm snap` (packages/testkit). Do not edit by hand: run `pnpm snap --update ' + name + '` and review the diff.',
    '',
    '## Input',
    '',
    ...table(['Field', 'Value'], [['Prefix', PREFIX_TEXT.todo]]),
    '',
    '## Error',
    '',
    'The runner cannot run this fixture yet. This records the current behavior; promote the fixture when it runs.',
    '',
    fenced('', `${error.name}: ${error.message}`.replace(/[\u0000-\u0008\u000b-\u001f\u007f-\u009f]/g, '')),
    '',
    '## Outcome',
    '',
    '- Final state: not run.',
    '- Prefix expectations: todo.',
    '',
  ].join('\n');
}
