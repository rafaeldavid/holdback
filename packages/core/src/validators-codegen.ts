// Generates validators.generated.ts: Ajv's standalone code for every schema in spec/schemas, compiled ahead of time
// so that importing core generates no code (T-233). A Cloudflare Worker counts its start-up against a CPU limit of
// 1 s, and compiling these schemas at import took most of it (measured, T-233); a Worker may never generate code
// inside a request either (T-029). Run `node packages/core/scripts/validators.ts` after a schema change;
// validators.test.ts fails while the checked-in file is stale.
//
// Build time only: this module compiles code, so nothing a Worker imports may import it. It imports packages only, no
// sibling module, so Node runs it straight from the TypeScript source.
import { readdirSync, readFileSync } from 'node:fs';
import Ajv2020 from 'ajv/dist/2020.js';
import standalone from 'ajv/dist/standalone/index.js';
import addFormats from 'ajv-formats';

/** The schema annotation on party-authored strings (ADR-0017 §9); parse.ts exports it as UNTRUSTED. */
export const UNTRUSTED_KEYWORD = 'x-holdback-untrusted';

/** Every schema file, sorted by name: `common` and the 17 the parsers use. Resolves from both src/ and dist/. */
export function schemaFiles(): { name: string; schema: { $id: string } }[] {
  const dir = new URL('../../../spec/schemas/', import.meta.url);
  return readdirSync(dir)
    .filter((f) => f.endsWith('.schema.json'))
    .sort()
    .map((file) => ({ name: file.replace('.schema.json', ''), schema: JSON.parse(readFileSync(new URL(file, dir), 'utf8')) as { $id: string } }));
}

/** The source of validators.generated.ts. */
export function validatorsSource(): string {
  const schemas = schemaFiles();
  // The options parse.ts compiled with before T-233, plus what standalone code needs. allErrors stays off: input is
  // untrusted, and the first error is enough to refuse it. The schemas are not checked against the 2020-12
  // meta-schema here; `pnpm validate:spec` does that, in strict mode, in CI. `lines` only puts each statement on its
  // own line, so a schema change shows as a readable diff. The generated code reads its formats from the name
  // `formats`, the parameter of the function it is wrapped in, so one copy of the code serves both sets.
  // ajv and ajv-formats are CommonJS; under NodeNext their default export arrives as `.default`.
  const ajv = new Ajv2020.default({ strict: true, allErrors: false, validateSchema: false, code: { optimize: false, source: true, lines: true, formats: Ajv2020._`formats` } });
  ajv.addKeyword({ keyword: UNTRUSTED_KEYWORD, schemaType: 'boolean' });
  // The only formats the schemas use (strict mode refuses any other). ajv-formats' definitions fix the shape the
  // code calls: `uri` a function, `date-time` an object with `validate`. validators.ts passes the same shapes.
  addFormats.default(ajv, ['uri', 'date-time']);
  for (const { schema } of schemas) ajv.addSchema(schema);
  const code = standalone.default(ajv, Object.fromEntries(schemas.map(({ name, schema }) => [name, schema.$id])));

  // Standalone code is CommonJS: `exports.<name> = validateN;`, and `require("…").default` for Ajv's runtime
  // helpers. The exports become the wrapper's return value, and each helper an import. The helpers are CommonJS
  // modules whose function is `exports.default`: Node and wrangler's bundler hand an import the whole module, and
  // Vitest hands it the function, so the import is read either way.
  const imports = new Map<string, string>();
  const body = code
    .replace(/^"use strict";\n?/, '')
    .replace(/require\("(ajv\/dist\/runtime\/[a-z0-9]+)"\)/g, (_match, path: string) => {
      const name = `runtime_${path.slice(path.lastIndexOf('/') + 1)}`;
      imports.set(name, path);
      return name;
    });
  if (body.includes('require(')) throw new Error('validators: the standalone code requires a module other than an Ajv runtime helper');
  return [
    '// @ts-nocheck',
    '// Generated by `node packages/core/scripts/validators.ts` from spec/schemas (T-233); do not edit.',
    "// Ajv's standalone code for every schema, compiled ahead of time so that importing core generates no code: a",
    '// Cloudflare Worker counts its start-up against a CPU limit, and may never generate code inside a request.',
    '// packages/core/src/validators.test.ts fails when this file is stale.',
    ...[...imports].sort().map(([name, path]) => `import ${name}_module from '${path}.js';`),
    ...[...imports].sort().map(([name]) => `const ${name} = { default: ${name}_module.default ?? ${name}_module };`),
    '',
    '/** A schema validator: true when `data` is valid; otherwise false, with the first error in `errors`. */',
    'export type SchemaValidator = ((data: unknown) => boolean) & { errors?: { instancePath: string; message?: string }[] | null };',
    '',
    '/** One validator per schema file, keyed by its name. `formats` supplies `uri` (a function) and `date-time` (an object with `validate`). */',
    'export function schemaValidators(formats: Record<string, unknown>): Record<string, SchemaValidator> {',
    'const exports = {};',
    body,
    'return exports;',
    '}',
    '',
  ].join('\n');
}
