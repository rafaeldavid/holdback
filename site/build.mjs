/** examples/try.ts bundled as plain ESM, not minified; viem and tweetnacl stay imports. Deterministic. */
export async function tryBundle(p = pins()) {
  const root = fileURLToPath(here('../'));
  const bundle = await rolldown({
    cwd: root,
    input: fileURLToPath(here('../examples/try.ts')),
    external: [/^viem(\/.*)?$/, 'tweetnacl'],
    platform: 'node',
    tsconfig: fileURLToPath(here('../examples/tsconfig.json')),
    logLevel: 'warn',
  });
  try {
    const { output } = await bundle.generate({ format: 'esm', minify: false, banner: tryBanner(p) });
    if (output.length !== 1 || output[0].type !== 'chunk') throw new Error(`bundling examples/try.ts gave ${output.length} files, not one`);
    return output[0].code;
  } finally {
    await bundle.close();
  }
}

